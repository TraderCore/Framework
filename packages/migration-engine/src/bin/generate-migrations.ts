#!/usr/bin/env bun

/**
 * Reads a directory of raw SQL migration files and writes a
 * `src/migrations.ts` file with all SQL inlined as string literals.
 *
 * Migration files must be named with a numeric prefix (e.g. 0000_init.sql, 0001_add_users.sql).
 * The numeric prefix is used as the migration version.
 *
 * Usage: tradercore-generate-migrations [--dir ./migrations] [--out ./src/migrations.ts]
 */

import fs from 'node:fs';
import path from 'node:path';

function parseArgs(args: string[]): { migrationsDir: string; outFile: string } {
    let migrationsDir = './migrations';
    let outFile = './src/migrations.ts';

    for (let i = 0; i < args.length; i++) {
        const next = args[i + 1];
        if (args[i] === '--dir' && next) {
            migrationsDir = next;
            i++;
        } else if (args[i] === '--out' && next) {
            outFile = next;
            i++;
        }
    }

    return {
        migrationsDir: path.resolve(migrationsDir),
        outFile: path.resolve(outFile),
    };
}

function main(): void {
    const { migrationsDir, outFile } = parseArgs(process.argv.slice(2));

    if (!fs.existsSync(migrationsDir)) {
        console.error(`Migrations directory not found: ${migrationsDir}`);
        console.error(
            'Create a migrations/ directory with numbered SQL files (e.g. 0000_init.sql).',
        );
        process.exit(1);
    }

    const sqlFiles = fs
        .readdirSync(migrationsDir)
        .filter((f) => f.endsWith('.sql'))
        .sort();

    if (sqlFiles.length === 0) {
        console.error(`No .sql files found in ${migrationsDir}`);
        process.exit(1);
    }

    const migrationEntries: string[] = [];

    for (const file of sqlFiles) {
        const match = file.match(/^(\d+)/);
        if (!match) {
            console.warn(
                `Skipping ${file} — filename must start with a numeric prefix`,
            );
            continue;
        }

        const version = match[1];
        const sqlPath = path.join(migrationsDir, file);
        const sql = fs.readFileSync(sqlPath, 'utf-8');

        migrationEntries.push(
            `    {\n        version: '${version}',\n        sql: \`${sql.replace(/`/g, '\\`').replace(/\$/g, '\\$')}\`,\n    }`,
        );
    }

    const content = `// Auto-generated by @tradercore/migration-engine — do not edit manually.
// Re-generate with: bun run db:generate
import type { PluginMigration } from '@tradercore/migration-engine';

export const migrations: PluginMigration[] = [
${migrationEntries.join(',\n')},
];
`;

    fs.writeFileSync(outFile, content, 'utf-8');

    console.log(
        `Generated ${migrationEntries.length} migration(s) → ${path.relative(process.cwd(), outFile)}`,
    );
}

main();
